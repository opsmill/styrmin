async def test_instance_generated_from_the_deployment_is_at_config_when_nothing_changed(
    graph,
):
    """Critique E7: the comparison agrees with what context generation stores."""
    graph.cluster.config = {
        "ingress_class": "traefik",
        "runtime_class": "default",
        "fqdn_suffix": "apps.example.com",
        "dedicated_ingress": {},
        "standard_storage": {"storage_class": "standard"},
    }
    graph.env_a.config = {
        "ip_whitelist": ["10.0.0.0/8"],
        "env_vars": {"LOG_LEVEL": "info", "REGION": "eu"},
        "scheduling": {"tolerations": [{"key": "env", "operator": "Exists"}]},
    }
    deployment = await deploy(
        graph,
        graph.env_a,
        "web",
        config={
            "db_size": "5Gi",
            "env_vars": {"LOG_LEVEL": "debug"},
            "scheduling": {"runtime_class": "kata"},
        },
    )

    assert _deployment_at_resolved_config(
        deployment,
        ClusterConfig.model_validate(graph.cluster.config),
        EnvironmentConfig.model_validate(graph.env_a.config),
    )
    counts = await fan_out_cluster_config(graph.cluster, graph.uow, USER_ID)
    assert update_tasks(graph) == []
    assert counts.skipped_noop == 1


