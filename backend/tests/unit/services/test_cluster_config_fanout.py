"""Unit tests for the cluster config fan-out (021-cluster-config-update, research D1 and D7).

Every deployment's active instance is generated by the real
``generate_instance_from_deployment`` against the fakes, and the redeploys run
the real ``redeploy_for_environment_update`` and ``apply_state`` with a mocked
Prefect manager. The tests therefore observe the ``UPDATE_INSTANCE`` tasks the
fan-out stores, and the comparison is checked against the resolved config that
context generation actually writes (critique E7).
"""

