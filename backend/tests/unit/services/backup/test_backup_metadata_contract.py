"""The ``Backup.metadata_`` key contract, and proof the type checker enforces it.

``Backup.metadata_`` is a plain ``JSON`` column, so nothing in the database tier
can tie the workflow that *writes* a key to the GraphQL resolver that *reads*
it. :class:`BackupMetadata` is that tie, and the failure it exists to prevent is
a spelling one: the Velero result payload the backup flow consumes calls the
expiry ``expiration``, while the persisted key is ``expires_at``. A writer
carrying the upstream spelling through would leave ``Backup.expiresAt`` null
forever — with no runtime error anywhere, because a plain ``dict`` accepts any
key.

So the contract is only worth having if the type checker actually rejects the
misspelling. ``ty`` is the project's authoritative checker, and
:func:`test_ty_rejects_a_misspelled_metadata_key` asserts that directly by
running it over a generated snippet. The snippet is generated into ``tmp_path``
rather than committed: a committed file containing the misspelling would fail
the repo-wide ``ty check`` in CI, which is the very check this test relies on.
"""

from __future__ import annotations

import shutil
import subprocess
from pathlib import Path

import pytest

from styrmin_backend.services.backup.metadata import (
    BackupMetadata,
    read_backup_metadata,
)

# Repo root: .../backend/tests/unit/services/backup/<this file>
REPO_ROOT = Path(__file__).resolve().parents[5]

# Every key the backup pipeline writes or reads, and nothing else. Pinned so
# adding a key is a deliberate edit here as well as in the TypedDict — the
# point of the contract is that writer and reader agree on this exact set.
PIPELINE_KEYS = frozenset({"timeout", "ttl", "ttl_source", "expires_at"})

# Velero's own spelling of the expiry, which is what reaches the workflow from
# the Prefect Variable payload. It must NOT be a usable metadata key.
VELERO_EXPIRY_SPELLING = "expiration"

# A module that writes the misspelled key both as a call argument and as an
# annotated local — the two shapes the real workflow uses.
_MISSPELLED_WRITER = '''\
"""Generated by test_backup_metadata_contract — not part of the codebase."""

from styrmin_backend.services.backup.metadata import BackupMetadata


def carry_velero_spelling_through() -> BackupMetadata:
    return {"expiration": "2026-09-02T12:00:00Z"}


def annotate_a_local() -> None:
    updates: BackupMetadata = {"expiration": "2026-09-02T12:00:00Z"}
    del updates
'''

# The same module with the persisted spelling, to prove the rejection above is
# about the key and not about the shape of the snippet.
_CORRECT_WRITER = '''\
"""Generated by test_backup_metadata_contract — not part of the codebase."""

from styrmin_backend.services.backup.metadata import BackupMetadata


def use_the_persisted_spelling() -> BackupMetadata:
    return {"expires_at": "2026-09-02T12:00:00Z"}


def annotate_a_local() -> None:
    updates: BackupMetadata = {"expires_at": "2026-09-02T12:00:00Z"}
    del updates
'''


def _ty_check(
    source: str, tmp_path: Path, name: str
) -> subprocess.CompletedProcess[str]:
    """Write *source* to a file under *tmp_path* and run ``ty check`` on it.

    Run from the repository root so ``ty`` picks up the project's
    ``[tool.ty]`` configuration — in particular ``extra-paths = ["backend"]``,
    without which the ``styrmin_backend`` import would not resolve and the
    snippet would fail for the wrong reason.
    """
    probe = tmp_path / name
    probe.write_text(source)
    return subprocess.run(
        ["ty", "check", "--output-format", "concise", str(probe)],
        capture_output=True,
        text=True,
        cwd=REPO_ROOT,
    )


def test_backup_metadata_declares_exactly_the_pipeline_keys() -> None:
    """The TypedDict is the single declaration of the persisted key names.

    Both halves matter: a key missing from the set means a writer cannot
    persist it, and an extra key means something is being written that no
    reader projects.
    """
    assert set(BackupMetadata.__annotations__) == set(PIPELINE_KEYS)


def test_velero_expiry_spelling_is_not_a_metadata_key() -> None:
    """``expiration`` is Velero's field name, not ours — the rename is the trap."""
    assert VELERO_EXPIRY_SPELLING not in BackupMetadata.__annotations__
    assert "expires_at" in BackupMetadata.__annotations__


def test_read_backup_metadata_narrows_without_copying_or_validating() -> None:
    """The reader-side narrowing is a type-level operation only.

    It must not copy (readers compare identity in nothing, but a copy would
    quietly diverge from the row) and must not validate — a hand-edited row
    holding a wrong-typed value has to reach the reader's own degrade-to-null
    guard rather than raising inside a GraphQL resolver.
    """
    raw = {"ttl": "2160h", "ttl_source": "environment"}
    assert read_backup_metadata(raw) is raw

    # ``metadata_`` is NULL on rows written before the column carried anything.
    assert read_backup_metadata(None) == {}

    # A stored value of the wrong type is passed straight through.
    corrupt = {"expires_at": 1234}
    assert read_backup_metadata(corrupt) is corrupt


@pytest.mark.skipif(
    shutil.which("ty") is None,
    reason="ty is not on PATH; the key contract can only be proven by the checker",
)
def test_ty_rejects_a_misspelled_metadata_key(tmp_path: Path) -> None:
    """``ty`` refuses Velero's ``expiration`` spelling where the contract applies.

    This is the whole point of the TypedDict: a bare ``dict[str, Any]`` accepts
    the misspelling, persists it, and leaves ``Backup.expiresAt`` null with no
    signal short of an E2E.
    """
    result = _ty_check(_MISSPELLED_WRITER, tmp_path, "misspelled_writer.py")

    assert result.returncode != 0, (
        f"ty accepted a misspelled metadata key.\n"
        f"stdout:\n{result.stdout}\nstderr:\n{result.stderr}"
    )
    combined = result.stdout + result.stderr
    assert "invalid-key" in combined, combined
    assert VELERO_EXPIRY_SPELLING in combined, combined
    assert "BackupMetadata" in combined, combined


@pytest.mark.skipif(
    shutil.which("ty") is None,
    reason="ty is not on PATH; the key contract can only be proven by the checker",
)
def test_ty_accepts_the_persisted_metadata_key(tmp_path: Path) -> None:
    """The control: the same snippet with ``expires_at`` type-checks clean.

    Without this, a snippet that failed for an unrelated reason (an unresolved
    import, say) would make the rejection test pass vacuously.
    """
    result = _ty_check(_CORRECT_WRITER, tmp_path, "correct_writer.py")

    assert result.returncode == 0, (
        f"ty rejected the persisted metadata key.\n"
        f"stdout:\n{result.stdout}\nstderr:\n{result.stderr}"
    )
